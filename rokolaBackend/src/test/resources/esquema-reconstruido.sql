    motivo             TEXT,                                                -- supuesto: TEXT y admite NULL (se lee con orEmpty())
    fecha_inicio       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,      -- supuesto: NOT NULL y valor por defecto
    fecha_fin          TIMESTAMPTZ,                                         -- NULL = indefinido
    activo             BOOLEAN     NOT NULL DEFAULT TRUE                    -- supuesto: valor por defecto
);

-- -----------------------------------------------------------------------------
-- accion_admin (bitácora del personal; ContratoSaltoService inserta, ContratoNocheService lee)
-- -----------------------------------------------------------------------------
CREATE TABLE public.accion_admin (
    id_accion          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- supuesto: identity bigint
    id_establecimiento BIGINT      NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    id_usuario         BIGINT      REFERENCES public.usuario (id_usuario),  -- admite NULL: se lee con LEFT JOIN
    tipo               VARCHAR(40) NOT NULL,   -- supuesto: longitud
    objetivo_tipo      VARCHAR(40),            -- supuesto: longitud y admite NULL
    objetivo_id        BIGINT,                 -- supuesto: sin FK (polimórfico según objetivo_tipo)
    detalle            JSONB,                  -- supuesto: JSONB (se lee detalle->>'texto'; se inserta NULL)
    -- El INSERT no da fecha: el DEFAULT es obligatorio.
    fecha              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- tipo: literales vistos en el código (filtro de ContratoNocheService; solo 'saltar' se escribe hoy):
--   'saltar', 'bloquear', 'desbloquear', 'extender_bloqueo', 'retirar',
--   'pausar_solicitudes', 'reanudar_solicitudes', 'forzar_apertura',
--   'pausar_reproduccion', 'reanudar_reproduccion', 'mantenimiento', 'abrir_sesion', 'cerrar_sesion',
--   'editar_horario', 'editar_lista', 'activar_lista', 'crear_usuario', 'editar_usuario',
--   'desactivar_usuario', 'reactivar_usuario', 'restablecer_clave', 'editar_establecimiento',
--   'regenerar_qr', 'editar_evento', 'editar_umbrales', 'vincular_pantalla', 'desvincular_pantalla',
--   'error_youtube', 'intento_no_permitido'.
--   Sin CHECK: el código filtra por esta lista justamente porque la base puede tener otros tipos.
-- objetivo_tipo: literal visto: 'cancion'.
