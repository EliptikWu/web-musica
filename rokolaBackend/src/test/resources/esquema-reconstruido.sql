-- =============================================================================
-- Esquema reconstruido de la base de datos de Rokola (PostgreSQL 16)
-- =============================================================================
-- Qué es: un script DDL que recrea, lo más fielmente que permite el código, el
-- esquema que usa el backend Spring Boot/Kotlin de rokolaBackend.
--
-- Origen: reconstruido el 2026-11-12 a partir del código del backend (entidades
-- JPA con @Table/@Column, convertidores de enumeraciones y todas las consultas SQL
-- de JdbcTemplate en compat/, reproduccion/, solicitud/, voto/, youtube/, etc.).
-- La tabla api_idempotencia se copia tal cual del doc 04 («Pendiente del backend»,
-- punto 12).
--
-- NO está verificado contra la base real de Railway (está fuera de línea y nadie
-- tiene acceso) y el repositorio no tiene migraciones de Flyway. Puede diferir de
-- la base real en tipos, longitudes, valores por defecto, índices y restricciones.
--
-- Uso: SOLO para levantar el backend en local (Docker) y hacer pruebas. No se usa
-- en producción ni como migración.
--
-- Convenciones:
--   * «-- supuesto: ...» marca un tipo o restricción que el código no prueba.
--   * Las columnas de texto tipo enumeración sin conjunto cerrado probado no llevan
--     CHECK: un comentario lista los literales vistos en el código.
--   * Los CHECK que sí existen son los que el propio código nombra (ck_...) y cuyo
--     convertidor rechaza cualquier otro valor.
-- =============================================================================

SET client_encoding = 'UTF8';
SET search_path = public;

-- -----------------------------------------------------------------------------
-- rol (usuario/Rol.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.rol (
    id_rol      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- smallint según Rol.kt
    nombre      VARCHAR(40)  NOT NULL,
    descripcion VARCHAR(250),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)  -- supuesto: nombre de la restricción (el código solo dice unique = true)
);
-- Valores de nombre vistos en el código: se comparan con lower(nombre) IN ('operador', 'administrador').

-- -----------------------------------------------------------------------------
-- establecimiento (establecimiento/Establecimiento.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.establecimiento (
    id_establecimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- supuesto: identity y no bigserial (GenerationType.IDENTITY admite ambos)
    nombre             VARCHAR(150) NOT NULL,
    slug               VARCHAR(100) NOT NULL,
    direccion          VARCHAR(250),
    zona_horaria       VARCHAR(60)  NOT NULL,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,               -- supuesto: valor por defecto
    fecha_creacion     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    CONSTRAINT uq_establecimiento_slug UNIQUE (slug)  -- supuesto: nombre de la restricción
);
-- Nota: el doc 04 (punto 14) propone una columna `tema` (rockola | vidrio | afiche);
-- el código del backend todavía no la usa, así que no se crea aquí.

-- -----------------------------------------------------------------------------
-- configuracion_servicio (establecimiento/ConfiguracionServicio.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.configuracion_servicio (
    id_configuracion            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento          BIGINT       NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    estado_manual               VARCHAR(20)  NOT NULL,
    max_solicitudes_dispositivo INTEGER      NOT NULL,
    duracion_max_seg            INTEGER      NOT NULL,
    minutos_bloqueo_repeticion  INTEGER      NOT NULL,
    aviso_privacidad_version    VARCHAR(40),
    fecha_modificacion          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    CONSTRAINT uq_configuracion_establecimiento UNIQUE (id_establecimiento),     -- supuesto: nombre (JoinColumn unique = true)
    -- EstadoServicio.kt nombra ck_config_estado y su convertidor rechaza otros valores.
    CONSTRAINT ck_config_estado CHECK (estado_manual IN ('disponible', 'pausado', 'mantenimiento'))
);

-- -----------------------------------------------------------------------------
-- horario_operacion (establecimiento/HorarioOperacion.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.horario_operacion (
    id_horario         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT   NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    dia_semana         SMALLINT NOT NULL,  -- ISO-8601: 1 = lunes … 7 = domingo (sin CHECK: el código no lo prueba)
    hora_inicio        TIME     NOT NULL,  -- supuesto: TIME sin zona (LocalTime)
    hora_fin           TIME     NOT NULL,  -- si es menor que hora_inicio, la franja termina al día siguiente
    activo             BOOLEAN  NOT NULL DEFAULT TRUE  -- supuesto: valor por defecto
);

-- -----------------------------------------------------------------------------
-- codigo_qr (establecimiento/CodigoQr.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.codigo_qr (
    id_qr              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT       NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    token_hash         VARCHAR(255) NOT NULL,
    fecha_creacion     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    fecha_revocacion   TIMESTAMPTZ,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,               -- supuesto: valor por defecto
    CONSTRAINT uq_codigo_qr_token_hash UNIQUE (token_hash)  -- supuesto: nombre de la restricción
);

-- -----------------------------------------------------------------------------
-- usuario (usuario/Usuario.kt; login en compat/ContratoPanelAcceso.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.usuario (
    id_usuario         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento BIGINT       NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    id_rol             SMALLINT     NOT NULL REFERENCES public.rol (id_rol),
    nombre             VARCHAR(120) NOT NULL,
    correo             VARCHAR(254) NOT NULL,
    password_hash      TEXT         NOT NULL,  -- bcrypt (BCryptPasswordEncoder de Spring Security)
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,   -- supuesto: valor por defecto
    cambiar_password   BOOLEAN      NOT NULL DEFAULT FALSE,  -- supuesto: valor por defecto
    intentos_fallidos  SMALLINT     NOT NULL DEFAULT 0,      -- supuesto: valor por defecto (el código lo limita a 32000)
    bloqueado_hasta    TIMESTAMPTZ,
    fecha_creacion     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    -- Usuario.kt nombra uq_usuario_correo_establecimiento.
    -- supuesto: sobre (id_establecimiento, correo) tal cual; el login compara lower(correo),
    -- así que la real podría ser un índice sobre lower(correo).
    CONSTRAINT uq_usuario_correo_establecimiento UNIQUE (id_establecimiento, correo)
);

-- -----------------------------------------------------------------------------
-- evento_calendario
-- supuesto: tabla mínima. Sesion.kt dice que existe pero «todavía no tiene entidad
-- propia» y ninguna consulta la lee; solo se crea para que la FK de sesion tenga destino.
-- -----------------------------------------------------------------------------
CREATE TABLE public.evento_calendario (
    id_evento_calendario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento   BIGINT      NOT NULL REFERENCES public.establecimiento (id_establecimiento),  -- supuesto
    nombre               VARCHAR(150),  -- supuesto
    tipo_evento          VARCHAR(60),   -- supuesto (sesion.tipo_evento tiene la misma longitud)
    fecha_inicio         TIMESTAMPTZ,   -- supuesto
    fecha_fin            TIMESTAMPTZ    -- supuesto
);

-- -----------------------------------------------------------------------------
-- sesion (sesion/Sesion.kt)
-- La base NO impide dos sesiones abiertas a la vez (SesionRepository.kt lo dice
-- explícitamente; el código toma la abierta más reciente). No se añade índice único.
-- -----------------------------------------------------------------------------
CREATE TABLE public.sesion (
    id_sesion            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento   BIGINT      NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    id_evento_calendario BIGINT      REFERENCES public.evento_calendario (id_evento_calendario),  -- supuesto: que exista la FK
    fecha_apertura       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    fecha_cierre         TIMESTAMPTZ,
    tipo_evento          VARCHAR(60),
    estado               VARCHAR(20) NOT NULL,
    indice_lista_defecto INTEGER     NOT NULL DEFAULT 1,  -- supuesto: por defecto 1 (RotacionCasa: «el índice comienza en 1»)
    -- EstadoSesion.kt nombra ck_sesion_estado y su convertidor rechaza otros valores.
    CONSTRAINT ck_sesion_estado CHECK (estado IN ('abierta', 'cerrada'))
);

-- -----------------------------------------------------------------------------
-- cancion (cancion/Cancion.kt; INSERT ... ON CONFLICT (youtube_video_id) en
-- ContratoParticipacionService.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.cancion (
    id_cancion        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youtube_video_id  VARCHAR(30)  NOT NULL,
    titulo            VARCHAR(300) NOT NULL,
    artista           VARCHAR(200),
    canal             VARCHAR(200),
    categoria         VARCHAR(100),
    duracion_seg      INTEGER      NOT NULL,
    miniatura_url     TEXT,
    categoria_youtube VARCHAR(100),
    embebible         BOOLEAN      NOT NULL,
    disponibilidad    VARCHAR(30)  NOT NULL,
    ultima_validacion TIMESTAMPTZ,
    -- El INSERT de ContratoParticipacionService no da fecha_creacion: el DEFAULT es obligatorio.
    fecha_creacion    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cancion_youtube_video_id UNIQUE (youtube_video_id),  -- objetivo de ON CONFLICT; supuesto: nombre
    -- Disponibilidad.kt nombra ck_cancion_disponibilidad y su convertidor rechaza otros valores.
    CONSTRAINT ck_cancion_disponibilidad CHECK (disponibilidad IN ('disponible', 'no_disponible', 'restringida', 'desconocida'))
);

-- -----------------------------------------------------------------------------
-- dispositivo (dispositivo/Dispositivo.kt; ON CONFLICT (id_establecimiento, device_hash)
-- en AccesoService.kt y ContratoDispositivoService.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.dispositivo (
    id_dispositivo         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento     BIGINT       NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    device_hash            VARCHAR(255) NOT NULL,  -- SHA-256 hex del UUID (contrato) o HMAC del token (flujo QR antiguo)
    tipo                   VARCHAR(30)  NOT NULL,
    primer_acceso          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    ultimo_acceso          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    aviso_privacidad_fecha TIMESTAMPTZ,
    -- Dispositivo.kt nombra uq_dispositivo_est_hash; es el objetivo de ON CONFLICT.
    CONSTRAINT uq_dispositivo_est_hash UNIQUE (id_establecimiento, device_hash),
    -- TipoDispositivo.kt nombra ck_dispositivo_tipo y su convertidor rechaza otros valores.
    CONSTRAINT ck_dispositivo_tipo CHECK (tipo IN ('movil', 'tableta', 'otro'))
);

-- -----------------------------------------------------------------------------
-- solicitud (solicitud/Solicitud.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.solicitud (
    id_solicitud               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion                  BIGINT      NOT NULL REFERENCES public.sesion (id_sesion),
    id_cancion                 BIGINT      NOT NULL REFERENCES public.cancion (id_cancion),
    id_dispositivo_solicitante BIGINT      NOT NULL REFERENCES public.dispositivo (id_dispositivo),
    fecha_solicitud            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    estado                     VARCHAR(25) NOT NULL DEFAULT 'pendiente',        -- supuesto: valor por defecto
    motivo_estado              TEXT,
    -- EstadoSolicitud.kt dice «Estados permitidos por ck_solicitud_estado» y su convertidor rechaza otros.
    -- En SQL solo se escriben pendiente, reproduciendo, reproducida, saltada, no_disponible y bloqueada;
    -- expirada y retirada vienen del enum (nadie las escribe todavía).
    CONSTRAINT ck_solicitud_estado CHECK (estado IN (
        'pendiente', 'reproduciendo', 'reproducida', 'saltada',
        'no_disponible', 'bloqueada', 'expirada', 'retirada'))
);
-- supuesto: no hay índice único de «una solicitud viva por canción y sesión»; el código lo
-- evita bajo el bloqueo de la fila de sesion (ORDER BY id_solicitud ... LIMIT 1 sugiere que la
-- base no lo impide).
CREATE INDEX idx_solicitud_sesion_estado ON public.solicitud (id_sesion, estado);  -- supuesto: índice de apoyo

-- -----------------------------------------------------------------------------
-- voto (voto/Voto.kt)
-- -----------------------------------------------------------------------------
CREATE TABLE public.voto (
    id_voto        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud   BIGINT      NOT NULL REFERENCES public.solicitud (id_solicitud),
    id_dispositivo BIGINT      NOT NULL REFERENCES public.dispositivo (id_dispositivo),
    fecha_voto     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- supuesto: valor por defecto
    activo         BOOLEAN     NOT NULL DEFAULT TRUE,               -- supuesto: valor por defecto
    fecha_retiro   TIMESTAMPTZ
);
-- VotoService.kt: «El índice parcial único de `voto` sigue siendo la última defensa en la BD».
-- supuesto: nombre y columnas exactas; se infiere un voto activo por (solicitud, dispositivo) (RN-04).
CREATE UNIQUE INDEX uq_voto_activo_solicitud_dispositivo
    ON public.voto (id_solicitud, id_dispositivo) WHERE activo;

-- -----------------------------------------------------------------------------
-- lista_defecto (solo SQL: ContratoEstadoService, ContratoNocheService,
-- ReproduccionAutomaticaService, ReproduccionGestionService)
-- -----------------------------------------------------------------------------
CREATE TABLE public.lista_defecto (
    id_lista           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- supuesto: identity bigint
    id_establecimiento BIGINT       NOT NULL REFERENCES public.establecimiento (id_establecimiento),
    nombre             VARCHAR(120) NOT NULL,  -- supuesto: longitud y NOT NULL
    modo_rotacion      VARCHAR(20)  NOT NULL DEFAULT 'secuencial',  -- supuesto: longitud y valor por defecto
    activa             BOOLEAN      NOT NULL DEFAULT FALSE           -- supuesto: valor por defecto
);
-- modo_rotacion: literales vistos en el código: 'aleatorio' (comparado tal cual; ContratoNocheService
-- dice «La base dice aleatorio») y, por exclusión, 'secuencial'. Sin CHECK.
-- supuesto: no hay índice único de «una lista activa por establecimiento»; el código toma
-- ORDER BY id_lista DESC LIMIT 1.

-- -----------------------------------------------------------------------------
-- elemento_lista (solo SQL)
-- -----------------------------------------------------------------------------
CREATE TABLE public.elemento_lista (
    id_elemento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- supuesto: identity bigint
    id_lista    BIGINT  NOT NULL REFERENCES public.lista_defecto (id_lista) ON DELETE CASCADE,  -- supuesto: ON DELETE CASCADE
    id_cancion  BIGINT  NOT NULL REFERENCES public.cancion (id_cancion),
    orden       INTEGER NOT NULL  -- supuesto: tipo y NOT NULL (se ordena por orden, id_elemento)
);

-- -----------------------------------------------------------------------------
-- reproduccion (solo SQL: ReproduccionGestionService, ReproduccionConsultaRepository,
-- ContratoPantallaService, ContratoSaltoService, ...)
-- -----------------------------------------------------------------------------
CREATE TABLE public.reproduccion (
    id_reproduccion       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- RETURNING id_reproduccion; supuesto: identity bigint
    id_sesion             BIGINT      NOT NULL REFERENCES public.sesion (id_sesion),
    id_cancion            BIGINT      NOT NULL REFERENCES public.cancion (id_cancion),
    id_solicitud          BIGINT      REFERENCES public.solicitud (id_solicitud),        -- NULL cuando suena la lista de la casa
    id_elemento           BIGINT      REFERENCES public.elemento_lista (id_elemento),    -- NULL cuando suena una solicitud
    fecha_inicio          TIMESTAMPTZ,  -- supuesto: admite NULL (el código filtra fecha_inicio IS NOT NULL); siempre se inserta
    fecha_fin             TIMESTAMPTZ,
    segundos_reproducidos INTEGER     NOT NULL DEFAULT 0,  -- supuesto: NOT NULL y por defecto 0 (se usa GREATEST(segundos_reproducidos, ?))
    resultado             VARCHAR(20) NOT NULL             -- supuesto: longitud
);
-- resultado: literales vistos en el código: 'iniciada', 'completada', 'saltada', 'fallida'.
-- Sin CHECK: el código valida el conjunto en finalizar(), pero no prueba una restricción en la BD.
-- supuesto: tampoco hay CHECK de que exactamente uno de id_solicitud / id_elemento sea no nulo.
-- ReproduccionConsultaRepository.kt: «El indice parcial uq_reproduccion_activa_sesion garantiza
-- como maximo una fila» con resultado = 'iniciada' por sesión.
CREATE UNIQUE INDEX uq_reproduccion_activa_sesion
    ON public.reproduccion (id_sesion) WHERE resultado = 'iniciada';

-- -----------------------------------------------------------------------------
-- bloqueo_contenido (solo SQL)
