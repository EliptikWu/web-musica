-- La plataforma (RF-064, ADR-29): quien crea bares y cuentas. Va aparte de `usuario`, que
-- siempre pertenece a un bar: una cuenta de bar nunca puede volverse superadmin por su rol.
CREATE TABLE IF NOT EXISTS public.superadmin (
    id_superadmin     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(120) NOT NULL,
    correo            VARCHAR(254) NOT NULL,
    password_hash     TEXT         NOT NULL,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    cambiar_password  BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos SMALLINT     NOT NULL DEFAULT 0,
    bloqueado_hasta   TIMESTAMPTZ,
    fecha_creacion    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_superadmin_correo ON public.superadmin (lower(correo));
