-- Lo que el código ya usaba y ninguna migración creaba (doc 04, pendiente 18), y la noche abierta
-- a mano (RF-037). Con IF NOT EXISTS: en la base real pudieron crearse a mano.

-- RF-058, ADR-23: pantallas del bar. Del token solo se guarda su SHA-256.
CREATE TABLE IF NOT EXISTS public.pantalla_vinculo (
    id_pantalla           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_establecimiento    BIGINT      NOT NULL REFERENCES public.establecimiento (id_establecimiento) ON DELETE CASCADE,
    token_hash            CHAR(64)    NOT NULL UNIQUE,
    codigo                CHAR(6),
    codigo_expira_en      TIMESTAMPTZ,
    estado                VARCHAR(12) NOT NULL CHECK (estado IN ('esperando', 'vinculada', 'revocada')),
    nombre                VARCHAR(40),
    id_usuario_vinculador BIGINT REFERENCES public.usuario (id_usuario),
    vinculada_en          TIMESTAMPTZ,
    ultimo_reporte        TIMESTAMPTZ,
    fecha_creacion        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Dos pantallas del mismo bar no pueden esperar con el mismo código.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pantalla_codigo_vigente
    ON public.pantalla_vinculo (id_establecimiento, codigo) WHERE codigo IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_pantalla_bar_estado ON public.pantalla_vinculo (id_establecimiento, estado);

-- La entidad CodigoQr la mapea; sin ella, GET /bares/{slug}/qr-publico responde 500.
ALTER TABLE public.codigo_qr ADD COLUMN IF NOT EXISTS url_publica VARCHAR(2048);

-- RF-037: una noche abierta a mano fuera del horario atiende hasta que se cierre.
ALTER TABLE public.sesion ADD COLUMN IF NOT EXISTS fuera_de_horario BOOLEAN NOT NULL DEFAULT FALSE;
